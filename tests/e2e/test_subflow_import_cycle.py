"""End-to-end coverage for Workflow nodes whose workflow contains itself.

A Workflow node runs a saved workflow file. If that workflow holds a Workflow node pointing back at
it, directly or through another workflow, running it must stop with an error that names the cycle
instead of importing workflows inside workflows until the engine dies. A workflow that is merely
reused, or nested inside another without looping, must keep running.

The recursive workflows are committed saved workflows in ``fixtures/workflow_node_library``, each a
Start Flow -> Workflow node -> End Flow graph. They are generated by
``fixtures/generate_shout_workflow_fixture.py`` through the engine's real workflow save.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import TYPE_CHECKING, NamedTuple
from unittest.mock import AsyncMock

import pytest

from griptape_nodes.exe_types.flow import ControlFlow
from griptape_nodes.retained_mode.events.base_events import ExecutionGriptapeNodeEvent
from griptape_nodes.retained_mode.events.execution_events import (
    NodeErrorEvent,
    StartFlowRequest,
    StartFlowResultFailure,
    StartFlowResultSuccess,
)
from griptape_nodes.retained_mode.events.flow_events import (
    CreateFlowRequest,
    CreateFlowResultSuccess,
    GetTopLevelFlowRequest,
    GetTopLevelFlowResultSuccess,
)
from griptape_nodes.retained_mode.events.library_events import (
    RegisterLibraryFromFileRequest,
    RegisterLibraryFromFileResultSuccess,
)
from griptape_nodes.retained_mode.events.parameter_events import SetParameterValueRequest
from griptape_nodes.retained_mode.events.workflow_events import (
    RunWorkflowFromScratchRequest,
    RunWorkflowFromScratchResultSuccess,
)

if TYPE_CHECKING:
    from collections.abc import Callable

    from griptape_nodes.retained_mode.engine import Engine

pytestmark = pytest.mark.timeout(300, method="thread")

FIXTURE_LIBRARY_DIR = Path(__file__).parent / "fixtures" / "workflow_node_library"
FIXTURE_LIBRARY_JSON_TEMPLATE = FIXTURE_LIBRARY_DIR / "griptape_nodes_library.json"
FIXTURE_NODE_FILE = FIXTURE_LIBRARY_DIR / "workflow_node_nodes.py"
WORKFLOW_FILES = [
    FIXTURE_LIBRARY_DIR / "shout_workflow.py",
    FIXTURE_LIBRARY_DIR / "recursive_workflow.py",
    FIXTURE_LIBRARY_DIR / "cycle_a_workflow.py",
    FIXTURE_LIBRARY_DIR / "cycle_b_workflow.py",
    FIXTURE_LIBRARY_DIR / "nested_workflow.py",
]
LIBRARY_NAME = "Workflow Node Library"


class FixtureWorkflow(NamedTuple):
    """A fixture workflow's Workflow node type and the stem of its file."""

    node_type: str
    stem: str


RECURSIVE = FixtureWorkflow(node_type="RecursiveWorkflow", stem="recursive_workflow")
CYCLE_A = FixtureWorkflow(node_type="CycleAWorkflow", stem="cycle_a_workflow")
CYCLE_B = FixtureWorkflow(node_type="CycleBWorkflow", stem="cycle_b_workflow")
NESTED = FixtureWorkflow(node_type="NestedWorkflow", stem="nested_workflow")


class TestSubflowImportCycle:
    """Running Workflow nodes that contain themselves or each other."""

    @pytest.fixture
    def library_dir(self, tmp_path: Path, engine: Engine, materialize_library: Callable[..., Path]) -> Path:
        """Register the fixture library with the recursive workflow node types; return its directory."""
        library_json = materialize_library(
            tmp_path / "library",
            template=FIXTURE_LIBRARY_JSON_TEMPLATE,
            node_file=FIXTURE_NODE_FILE,
            extra_files=WORKFLOW_FILES,
        )
        schema = json.loads(library_json.read_text())
        for workflow in (RECURSIVE, CYCLE_A, CYCLE_B, NESTED):
            schema["workflow_nodes"].append(
                {
                    "node_type": workflow.node_type,
                    "workflow_path": f"{workflow.stem}.py",
                    "metadata": {
                        "category": "test",
                        "description": workflow.node_type,
                        "display_name": workflow.node_type,
                    },
                }
            )
        library_json.write_text(json.dumps(schema, indent=2))

        register_result = engine.handle_request(RegisterLibraryFromFileRequest(file_path=str(library_json)))
        assert isinstance(register_result, RegisterLibraryFromFileResultSuccess), register_result
        return library_json.parent

    @pytest.fixture
    def aput_event(self, engine: Engine, monkeypatch: pytest.MonkeyPatch) -> AsyncMock:
        """Spy on the engine's event bus, still delivering every event to the real one."""
        event_manager = engine.event_manager
        real_aput_event = event_manager.aput_event
        spy = AsyncMock(spec=real_aput_event, wraps=real_aput_event)
        monkeypatch.setattr(event_manager, "aput_event", spy)
        return spy

    @pytest.mark.asyncio
    async def test_self_referencing_workflow_node_refuses_to_run(
        self,
        library_dir: Path,
        engine: Engine,
        create_node: Callable[..., str],
        aput_event: AsyncMock,
    ) -> None:
        """A Workflow node whose workflow contains a Workflow node pointing back at it fails naming the cycle."""
        parent_flow = self._new_parent_flow(engine)
        create_node(RECURSIVE.node_type, "Outer", parent_flow, library_name=LIBRARY_NAME)

        result = await engine.ahandle_request(StartFlowRequest(flow_name=parent_flow, flow_node_name="Outer"))

        assert isinstance(result, StartFlowResultFailure), result
        details = str(result.result_details)
        key = self._key(library_dir, RECURSIVE)
        assert f"Attempted to import workflow '{key}'" in details, details
        assert f"'{key}' contains itself" in details, details
        # The parent flow, the imported copy, and nothing deeper.
        assert self._flow_count(engine) == 2, details  # noqa: PLR2004
        self._assert_node_errors_name_the_cycle(aput_event, levels=2)

    @pytest.mark.asyncio
    async def test_mutually_referencing_workflow_nodes_refuse_to_run(
        self,
        library_dir: Path,
        engine: Engine,
        create_node: Callable[..., str],
        aput_event: AsyncMock,
    ) -> None:
        """Two workflows that each contain a Workflow node for the other fail naming the cycle."""
        parent_flow = self._new_parent_flow(engine)
        create_node(CYCLE_A.node_type, "Outer", parent_flow, library_name=LIBRARY_NAME)

        result = await engine.ahandle_request(StartFlowRequest(flow_name=parent_flow, flow_node_name="Outer"))

        assert isinstance(result, StartFlowResultFailure), result
        details = str(result.result_details)
        key = self._key(library_dir, CYCLE_A)
        assert f"Attempted to import workflow '{key}'" in details, details
        assert f"'{key}' contains itself" in details, details
        # The parent flow, A's copy, and B's copy inside it; the second A is refused.
        assert self._flow_count(engine) == 3, details  # noqa: PLR2004
        self._assert_node_errors_name_the_cycle(aput_event, levels=3)

    @pytest.mark.asyncio
    async def test_running_a_self_referencing_workflow_as_the_current_workflow_refuses_to_run(
        self,
        library_dir: Path,
        engine: Engine,
        aput_event: AsyncMock,
    ) -> None:
        """Loading the self-referencing workflow as the top-level workflow and running it fails, naming the cycle, after one level of import."""
        load_result = await engine.ahandle_request(
            RunWorkflowFromScratchRequest(file_path=str(library_dir / f"{RECURSIVE.stem}.py"))
        )
        assert isinstance(load_result, RunWorkflowFromScratchResultSuccess), load_result
        top_flow_result = engine.handle_request(GetTopLevelFlowRequest())
        assert isinstance(top_flow_result, GetTopLevelFlowResultSuccess), top_flow_result
        assert top_flow_result.flow_name is not None

        result = await engine.ahandle_request(StartFlowRequest(flow_name=top_flow_result.flow_name))

        assert isinstance(result, StartFlowResultFailure), result
        details = str(result.result_details)
        key = self._key(library_dir, RECURSIVE)
        assert f"Attempted to import workflow '{key}'" in details, details
        assert f"'{key}' contains itself" in details, details
        # The opened workflow's flow and the one imported copy, and nothing deeper.
        assert self._flow_count(engine) == 2, details  # noqa: PLR2004
        self._assert_node_errors_name_the_cycle(aput_event, levels=2, outer_node_name="Inner Workflow")

    @pytest.mark.usefixtures("library_dir")
    @pytest.mark.asyncio
    async def test_same_workflow_used_twice_in_one_flow_still_runs(
        self,
        engine: Engine,
        create_node: Callable[..., str],
        connect: Callable[..., None],
    ) -> None:
        """Two Workflow nodes for the same workflow side by side are not a cycle."""
        parent_flow = self._new_parent_flow(engine)
        create_node("ShoutWorkflow", "First", parent_flow, library_name=LIBRARY_NAME)
        create_node("ShoutWorkflow", "Second", parent_flow, library_name=LIBRARY_NAME)
        connect("First", "exec_out", "Second", "exec_in")
        connect("First", "result", "Second", "text")
        set_result = engine.handle_request(
            SetParameterValueRequest(parameter_name="text", node_name="First", value="hey")
        )
        assert set_result.succeeded(), set_result

        result = await engine.ahandle_request(StartFlowRequest(flow_name=parent_flow, flow_node_name="First"))

        assert isinstance(result, StartFlowResultSuccess), result
        assert engine.node_manager.get_node_by_name("First").parameter_output_values.get("result") == "HEY!"
        assert engine.node_manager.get_node_by_name("Second").parameter_output_values.get("result") == "HEY!!"

    @pytest.mark.usefixtures("library_dir")
    @pytest.mark.asyncio
    async def test_workflow_nested_inside_another_without_a_loop_still_runs(
        self,
        engine: Engine,
        create_node: Callable[..., str],
    ) -> None:
        """A workflow containing a Workflow node for a different workflow is not a cycle."""
        parent_flow = self._new_parent_flow(engine)
        create_node(NESTED.node_type, "Outer", parent_flow, library_name=LIBRARY_NAME)
        set_result = engine.handle_request(
            SetParameterValueRequest(parameter_name="text", node_name="Outer", value="hello")
        )
        assert set_result.succeeded(), set_result

        result = await engine.ahandle_request(StartFlowRequest(flow_name=parent_flow, flow_node_name="Outer"))

        assert isinstance(result, StartFlowResultSuccess), result
        assert engine.node_manager.get_node_by_name("Outer").parameter_output_values.get("result") == "HELLO!"

    def _new_parent_flow(self, engine: Engine) -> str:
        engine.context_manager.push_workflow(workflow_name="import_cycle_parent")
        result = engine.handle_request(
            CreateFlowRequest(parent_flow_name=None, flow_name="ParentFlow", set_as_new_context=False)
        )
        assert isinstance(result, CreateFlowResultSuccess), result
        return result.flow_name

    def _key(self, library_dir: Path, workflow: FixtureWorkflow) -> str:
        """Return the registry key the engine uses for a library-shipped workflow file."""
        return (library_dir / workflow.stem).as_posix()

    def _flow_count(self, engine: Engine) -> int:
        return len(engine.object_manager.get_filtered_subset(type=ControlFlow))

    def _assert_node_errors_name_the_cycle(
        self, aput_event: AsyncMock, *, levels: int, outer_node_name: str = "Outer"
    ) -> None:
        """The outermost node error carries the cycle, and nested levels report errors of their own."""
        node_errors = self._node_errors(aput_event)
        assert len(node_errors) >= levels, node_errors
        outer = node_errors[-1]
        assert outer.node_name == outer_node_name, outer
        assert outer.error is not None, outer
        assert "contains itself" in outer.error.message, outer.error
        assert any(event.node_name != outer_node_name for event in node_errors), node_errors

    def _node_errors(self, aput_event: AsyncMock) -> list[NodeErrorEvent]:
        """Return the NodeErrorEvents published through the spied event bus, in order."""
        node_errors: list[NodeErrorEvent] = []
        for call in aput_event.call_args_list:
            event = call.args[0]
            if not isinstance(event, ExecutionGriptapeNodeEvent):
                continue
            payload = event.wrapped_event.payload
            if isinstance(payload, NodeErrorEvent):
                node_errors.append(payload)
        return node_errors
