"""End-to-end coverage for Workflow nodes that contain other Workflow nodes.

A failure several Workflow nodes down must be reported once, naming the node that failed, how
many nested Workflow nodes it was inside and the nodes in between, including groups and loops.
A workflow that is merely reused, or nested inside another, must keep running.

The workflows are committed saved workflows in ``fixtures/workflow_node_library``, each a
Start Flow -> Workflow node -> End Flow graph. The Countdown fixtures branch: they run the next
level on Then while their text is non-empty, and go straight to End (or to a failing node) on
Else. They are generated by ``fixtures/generate_shout_workflow_fixture.py`` through the engine's
real workflow save.
"""

