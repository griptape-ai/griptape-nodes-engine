    @pytest.mark.asyncio
    async def test_node_failing_in_nested_workflows_without_recursion_is_reported_once_with_the_depth(
        self,
        engine: Engine,
        library_dir: Path,  # noqa: ARG002 - registers the fixture library
        create_node: Callable[..., str],
        aput_event: AsyncMock,
    ) -> None:
        """A node failing two Workflow nodes down, in workflows that do not recurse, is named once with the depth."""
        parent_flow = self._new_parent_flow(engine)
        create_node(DEEPLY_NESTED_FAIL.node_type, "Outer", parent_flow, library_name=LIBRARY_NAME)

        result = await engine.ahandle_request(StartFlowRequest(flow_name=parent_flow, flow_node_name="Outer"))

        assert isinstance(result, StartFlowResultFailure), result
        details = str(result.result_details)
        assert details.count(RUN_SENTENCE) == 1, details
        assert details.count(FIXTURE_FAILURE_MESSAGE) == 1, details
        assert "node 'Failing', inside 2 nested Workflow nodes, failed" in details, details
        outer = self._node_errors(aput_event)[-1]
        assert outer.node_name == "Outer", outer
        assert outer.error is not None, outer
        assert outer.error.message.count(FIXTURE_FAILURE_MESSAGE) == 1, outer.error
        assert "did not finish" not in outer.error.message, outer.error
        assert outer.error.fields[FAILED_NODE_PATH_FIELD].split(PATH_SEPARATOR) == [
            "Inner Workflow",
            "Inner Workflow_1",
            "Failing",
        ], outer.error

    @pytest.mark.asyncio
    async def test_node_failing_in_nested_workflows_is_logged_at_error_once(
        self,
        engine: Engine,
        library_dir: Path,  # noqa: ARG002 - registers the fixture library
        create_node: Callable[..., str],
        caplog: pytest.LogCaptureFixture,
    ) -> None:
        """A failure two Workflow nodes down is logged at ERROR once, by the outermost run, not at every level."""
        parent_flow = self._new_parent_flow(engine)
        create_node(DEEPLY_NESTED_FAIL.node_type, "Outer", parent_flow, library_name=LIBRARY_NAME)

        with caplog.at_level(logging.ERROR, logger="griptape_nodes"):
            result = await engine.ahandle_request(StartFlowRequest(flow_name=parent_flow, flow_node_name="Outer"))

        assert isinstance(result, StartFlowResultFailure), result
        errors = self._error_messages(caplog)
        assert len(errors) == 1, errors
        assert errors[0].startswith("Attempted to run flow 'ParentFlow'"), errors
        assert FIXTURE_FAILURE_MESSAGE in errors[0], errors

