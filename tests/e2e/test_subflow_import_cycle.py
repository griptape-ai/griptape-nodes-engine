    @pytest.mark.asyncio
    async def test_self_referencing_workflow_node_refuses_to_run(
        self,
        library_dir: Path,
        engine: Engine,
        create_node: Callable[..., str],
        aput_event: AsyncMock,
        set_recursion_depth: Callable[[int], None],
    ) -> None:
        """A Workflow node whose workflow points back at it fails naming the cycle once past a limit of 1."""
        set_recursion_depth(1)
        parent_flow = self._new_parent_flow(engine)
        create_node(RECURSIVE.node_type, "Outer", parent_flow, library_name=LIBRARY_NAME)

        result = await engine.ahandle_request(StartFlowRequest(flow_name=parent_flow, flow_node_name="Outer"))

        assert isinstance(result, StartFlowResultFailure), result
        details = str(result.result_details)
        key = self._key(library_dir, RECURSIVE)
        assert f"Attempted to import workflow '{key}'" in details, details
        assert f"'{key}' contains itself" in details, details
        # The parent flow, the imported copy, and the one copy it may hold of itself; nothing deeper.
        assert self._flow_count(engine) == 3, details  # noqa: PLR2004
        self._assert_node_errors_name_the_cycle(aput_event, levels=2)

