"""End-to-end coverage for Workflow nodes whose workflow contains itself.

A Workflow node runs a saved workflow file. If that workflow holds a Workflow node pointing back at
it, directly or through another workflow, it may recurse up to the `max_workflow_recursion_depth`
setting. Past that, running it must stop with an error that names the cycle instead of importing
workflows inside workflows until the engine dies. A workflow that is merely reused, or nested inside
another without looping, must keep running.

The recursive workflows are committed saved workflows in ``fixtures/workflow_node_library``, each a
Start Flow -> Workflow node -> End Flow graph. The Countdown fixture branches: it recurses on Then
while its text is non-empty, and goes straight to End on Else. They are generated by
``fixtures/generate_shout_workflow_fixture.py`` through the engine's real workflow save.
"""

